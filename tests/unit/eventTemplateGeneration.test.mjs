import { describe, it, expect, vi } from "vitest";

vi.mock("../../controllers/databaseController.js", () => ({ prisma: {}, default: {} }));

const { computeNextGenerationDate, computeTargetEventDate } = await import("../../services/eventTemplateService.js");

const iso = (d) => d.toISOString().slice(0, 10);
// Monday 5 October 2026 (UTC). Recurrence days: 1 = Monday, 5 = Friday.
const MON_FRI = { recurrenceType: "weekly", recurrenceDays: [1, 5], autoGenerateDrafts: true, draftAdvanceDays: 7 };

describe("weekly template draft generation", () => {
  it("schedules a generation for every recurrence day, not one per week", () => {
    // Generation fired Monday 5 Oct (for Monday 12 Oct); the next one is for Friday 16 Oct.
    const next = computeNextGenerationDate(MON_FRI, new Date("2026-10-05T00:00:05Z"));
    expect(next.toISOString()).toBe("2026-10-09T00:00:00.000Z");
    // Then Friday 9 Oct -> Monday 12 Oct (for Monday 19 Oct).
    const after = computeNextGenerationDate(MON_FRI, new Date("2026-10-09T00:00:05Z"));
    expect(after.toISOString()).toBe("2026-10-12T00:00:00.000Z");
  });

  it("targets the event draftAdvanceDays out, not the nearest weekday after today", () => {
    const tmpl = { ...MON_FRI, nextGenerateAt: new Date("2026-10-05T00:00:00Z") };
    expect(iso(computeTargetEventDate(tmpl, new Date("2026-10-05T00:00:05Z")))).toBe("2026-10-12");
    const fri = { ...MON_FRI, nextGenerateAt: new Date("2026-10-09T00:00:00Z") };
    expect(iso(computeTargetEventDate(fri, new Date("2026-10-09T00:00:05Z")))).toBe("2026-10-16");
  });

  it("handles an advance longer than a week on a single-day template", () => {
    const tmpl = { recurrenceType: "weekly", recurrenceDays: [1], autoGenerateDrafts: true, draftAdvanceDays: 14 };
    const next = computeNextGenerationDate(tmpl, new Date("2026-10-05T00:00:05Z"));
    expect(next.toISOString()).toBe("2026-10-12T00:00:00.000Z");
    expect(iso(computeTargetEventDate({ ...tmpl, nextGenerateAt: next }, new Date("2026-10-12T00:00:05Z")))).toBe("2026-10-26");
  });

  it("falls back to the next occurrence when a missed generation would target a past day", () => {
    const tmpl = { ...MON_FRI, nextGenerateAt: new Date("2026-09-01T00:00:00Z") };
    expect(iso(computeTargetEventDate(tmpl, new Date("2026-10-06T10:00:00Z")))).toBe("2026-10-09");
  });
});
